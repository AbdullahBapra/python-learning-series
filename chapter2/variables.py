

# variables are used for progamming to store a value in memory. just like container
# variables are used to store different types of data types such as integer, float, string,boolean,none etc.


a = 10  # a is stored with integer value 10

b = 90.555  # b is stored with float value 90.555

c = "hello world"  # c is stored with string value "hello world"

d = True  # d is stored with boolean value True

e = None  # e is stored with None value

print(a)
print(b)
print(c)
print(d)
print(e)

# rules of defining varaibles in Python

# 1. varaibles name should start with a letter or an underscore
# 2. varaibles name should not start with a number
# 3. varaibles name should not start with a special character
# 4. varaibles name should not start with a keyword
# 5. varaibles name should not contain any special character except underscore


